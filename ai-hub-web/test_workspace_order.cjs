const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(__dirname + '/public/index.html', 'utf8');
const start = html.indexOf('    function readWorkspaceOrder()');
const end = html.indexOf('    let currentContextMenuPath', start);
let saved = { order: ['c', 'b', 'a'], pins: ['b'] };
const ctx = vm.createContext({ localStorage: { getItem: () => JSON.stringify(saved) } });
vm.runInContext(html.slice(start, end), ctx);
assert.equal(ctx.sortedWorkspaceEntries({ a: {}, b: {}, c: {} }).map(([k]) => k).join(','), 'b,c,a');
saved = { order: ['c', 'b', 'a'], pins: [] };
assert.equal(ctx.sortedWorkspaceEntries({ a: {}, b: {}, c: {} }).map(([k]) => k).join(','), 'c,b,a');
let visible = ['a', 'b', 'c'];
saved = { order: ['a', 'b', 'c'], pins: [] };
ctx.document = { querySelectorAll: () => visible.map(k => ({ getAttribute: () => k })) };
ctx.normPath = p => p;
ctx.currentContextMenuPath = { rawPath: 'c', isWorkspace: true };
ctx.closePathContextMenu = () => {};
ctx.loadWorkspaceTree = () => {};
ctx.localStorage.setItem = (k, value) => { saved = JSON.parse(value); };
ctx.changeWorkspaceOrder('pin');
visible = ['c', 'a', 'b'];
assert.deepEqual(saved.order, ['a', 'b', 'c'], 'Pin must preserve original order');
ctx.changeWorkspaceOrder('pin');
assert.equal(ctx.sortedWorkspaceEntries({ a: {}, b: {}, c: {} }).map(([k]) => k).join(','), 'a,b,c', 'Unpin returns workspace to original position');
assert.ok(html.includes('data-workspace-order="up"'));
assert.ok(html.includes('data-workspace-order="down"'));
assert.ok(html.includes('data-workspace-order="pin"'));
assert.ok(html.includes('workspace-pin-indicator'), 'Pinned workspace has a visible indicator');
assert.ok(html.includes("pinButton.textContent = isPinned ? 'Bỏ ghim' : 'Ghim lên đầu'"), 'Menu action matches pin state');
assert.ok(!html.includes('>Ghim / Bỏ ghim lên đầu</button>'));
assert.ok(html.includes('<svg class="workspace-running-spinner"'), 'Workspace uses a dedicated SVG loading ring');
assert.match(html, /\.workspace-running-spinner\s*\{[^}]*animation: hubLoadingSpin 1\.1s linear infinite;/, 'Workspace ring continuously rotates');
assert.match(html, /\.workspace-running-spinner \{ animation-duration: 3s; \}/, 'Reduced motion slows the status ring instead of freezing it');
console.log('Workspace order and running SVG spinner checks passed');
