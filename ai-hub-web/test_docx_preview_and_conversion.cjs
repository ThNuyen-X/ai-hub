const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname, 'public/index.html'), 'utf8');
const server = fs.readFileSync(path.join(__dirname, 'server.js'), 'utf8');
for (const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(m[1]);
assert.ok(!html.includes('docx-to-pdf'));
assert.ok(!html.includes('docx-pdf-status'));
assert.ok(!html.includes('filePreviewDocxPdfBtn'));
assert.ok(!server.includes('/api/docx-to-pdf'));
assert.ok(!server.includes('/api/docx-pdf-status'));
assert.ok(html.includes('getOrCreateDocxShadowRoot'));
assert.ok(html.includes('renderToken !== currentDocxRenderToken'));
assert.ok(html.includes('currentDocxAbortController.abort()'));
assert.ok(html.includes('id="filePreviewDocxScrollWrapper" tabindex="0" class="flex-1 min-h-0 min-w-0 overflow-auto'));
assert.ok(html.includes("docxContainer.classList.add('flex')"));
assert.ok(html.includes('#filePreviewBody { min-height: 0; }'));
assert.ok(html.includes('#filePreviewModal.is-expanded #filePreviewDialog'));
const start = html.indexOf('    window.toggleFilePreviewExpanded = function()');
const end = html.indexOf('    window.closeFilePreview', start);
assert.ok(start >= 0 && end > start);
const classes = new Set();
const attrs = {};
const modal = { classList: { toggle(c) { if (classes.has(c)) { classes.delete(c); return false; } classes.add(c); return true; } } };
const ctx = vm.createContext({window: {}, document: {getElementById(id) { return id === 'filePreviewModal' ? modal : {setAttribute(k,v) {attrs[k]=v;}};}}, currentPreviewData: {previewType:'docx'}, requestAnimationFrame: fn=>fn(), toggleDocxFitWidth: ()=>{ctx.fitCalls++;}, fitCalls:0});
vm.runInContext(html.slice(start,end),ctx);
ctx.window.toggleFilePreviewExpanded();
assert.equal(classes.has('is-expanded'),true);
assert.equal(attrs['aria-pressed'],'true');
assert.equal(ctx.fitCalls,1);
ctx.window.toggleFilePreviewExpanded();
assert.equal(classes.has('is-expanded'),false);
assert.equal(attrs['aria-pressed'],'false');
const types = require('./docx-pdf-service.cjs');
assert.equal(types.getPreviewFileType('.docx'),'docx');
assert.equal(types.getPreviewFileType('.pdf'),'pdf');
assert.equal(types.convertDocxToPdf,undefined);
console.log('DOCX: frontend syntax, conversion removal, scroll/flex guards and expand toggle behavior PASS');
