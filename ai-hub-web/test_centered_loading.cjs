const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const html = fs.readFileSync('public/index.html', 'utf8');
for (const match of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
assert.match(html, /\.live-progress-container\s*\{[^}]*justify-content: center;/);
assert.match(html, /class="live-progress-container" role="status" aria-live="polite"/);
assert.match(html, /class="progress-label sr-only"/);
assert.match(html, /class="agent-loading-tiles" aria-hidden="true">(?:<i><\/i>){3}<\/span>/);
assert.match(html, /\.agent-loading-tiles i\s*\{[^}]*display: block;[^}]*width: 9px;[^}]*height: 9px;[^}]*animation: agentTileFlip 1\.2s ease-in-out infinite;/);
assert.match(html, /nth-child\(2\) \{ animation-delay: -0\.8s;/);
assert.match(html, /nth-child\(3\) \{ animation-delay: -0\.4s;/);
assert.match(html, /@keyframes agentTileFlip\s*\{[\s\S]*?rotateY\(0deg\)[\s\S]*?rotateY\(180deg\)/);
assert.match(html, /prefers-reduced-motion: reduce\)\s*\{\s*\.agent-loading-tiles i \{ animation-name: agentTileFade;/);
for (const old of ['agent-loading-ring', 'agent-loading-gallery', 'agent-loading-scene']) assert.ok(!html.includes(old), old + ' removed');
assert.ok(html.includes('<svg class="workspace-running-spinner"'), 'Sidebar spinner preserved');
const finish = html.match(/function finishProgress\(customMsg\) \{([\s\S]*?)\n      \}/)[1];
assert.ok(finish.includes("row.querySelectorAll('.streaming-cursor')"));
assert.ok(finish.includes('progressEl.remove();'));
assert.ok(!finish.includes('setTimeout'));
assert.ok(html.indexOf('<div class="ai-content-body space-y-2.5"></div>') < html.indexOf('class="live-progress-container"'));
console.log('Centered loading: three flipping tiles, staggered animation, reduced motion and cleanup passed');
