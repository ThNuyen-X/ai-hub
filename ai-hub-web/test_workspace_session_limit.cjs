const assert = require('node:assert/strict');
const { MAX_WORKSPACE_SESSIONS, countWorkspaceSessions } = require('./workspace-session-limit.cjs');
assert.equal(MAX_WORKSPACE_SESSIONS, 20);
const stored = [{ id: 'one', name: 'Chat', tempName: 'temp', cwd: 'D:/Project' }];
const existing = { sessionId: 'temp', info: { cwd: '\\\\?\\D:\\PROJECT\\' } };
const pending = { sessionId: 'pending', info: { cwd: 'd:/project/' } };
assert.equal(countWorkspaceSessions('D:/project', stored, [existing, existing, pending]), 2);
assert.equal(countWorkspaceSessions('D:/other', stored, [existing, pending]), 0);
assert.equal(countWorkspaceSessions('D:/project', stored, [{ ...pending, isFinished: true }]), 1);
assert.equal(countWorkspaceSessions('D:/project', stored, [{ sessionId: 'other', resolvedDbId: 'one', info: { cwd: 'D:/project' } }]), 1);
const { makeWorkspaceSessionRoom } = require('./workspace-session-limit.cjs');
const full = Array.from({ length: 20 }, (_, i) => ({ id: String(i), cwd: 'D:/project', created_at: new Date(2026, 0, i + 1).toISOString() }));
const removed = [];
makeWorkspaceSessionRoom('d:/PROJECT', full.slice().reverse(), [], s => s.id === '0', s => removed.push(s.id));
assert.deepEqual(removed, ['1'], 'Oldest by creation date, excluding running sessions');
assert.throws(() => makeWorkspaceSessionRoom('D:/project', full, [], () => true, () => assert.fail('Must not delete running sessions')), /running sessions/);
const over = [...full, { id: 'extra', cwd: 'D:/project', created_at: '2027-01-01' }];
const pruned = [];
makeWorkspaceSessionRoom('D:/project', over, [], () => false, s => pruned.push(s.id));
assert.deepEqual(pruned, ['0', '1']);
assert.throws(() => makeWorkspaceSessionRoom('D:/project', full, [], () => false, () => { throw new Error('Deletion failed'); }), /Deletion failed/);
// Pinned sessions: not counted toward the limit and never pruned.
const pinnedIds = new Set(['0', '1', '2']);
const isPinned = s => pinnedIds.has(s.id);
assert.equal(countWorkspaceSessions('D:/project', full, [], isPinned), 17);
const none = [];
makeWorkspaceSessionRoom('D:/project', full, [], () => false, s => none.push(s.id), isPinned);
assert.deepEqual(none, [], '20 stored with 3 pinned: only 17 count, so a new session needs no pruning');
const withExtra = [...full, ...Array.from({ length: 3 }, (_, i) => ({ id: 'n' + i, cwd: 'D:/project', created_at: '2027-01-0' + (i + 1) }))];
const prunedPinned = [];
makeWorkspaceSessionRoom('D:/project', withExtra, [], () => false, s => prunedPinned.push(s.id), isPinned);
assert.deepEqual(prunedPinned, ['3'], '23 stored with 3 pinned counts 20, so the oldest unpinned (3) is pruned and pinned 0,1,2 are kept');
const allPinned = [];
makeWorkspaceSessionRoom('D:/project', full, [], () => false, s => allPinned.push(s.id), () => true);
assert.deepEqual(allPinned, [], 'Everything pinned: nothing is deleted');
const pendingPinned = { sessionId: 'p2', info: { cwd: 'D:/project' } };
assert.equal(countWorkspaceSessions('D:/project', [], [pendingPinned], s => s.id === 'p2'), 0, 'Pinned active session is not counted');
// Server-side prefs store (temp file, never the real user preferences).
const os = require('node:os'), fs = require('node:fs'), path = require('node:path');
const { createPrefs } = require('./hub-prefs.cjs');
const pinDir = fs.mkdtempSync(path.join(process.env.AI_HUB_SCRATCH_DIR || os.tmpdir(), 'prefs-'));
const pinFile = path.join(pinDir, 'prefs.json');
try {
  const a = createPrefs(pinFile);
  assert.equal(a.get().initialized, false);
  assert.equal(a.seed({}).seeded, false, 'Empty browser must not consume the one-time baseline');
  assert.equal(a.get().initialized, false);
  assert.equal(a.setSessionPin('s1', true), true);
  assert.equal(a.setSessionPin('s1', true), false);
  assert.equal(a.seed({ sessionPins: ['s2', 's1', 5, ''], workspaceOrder: { order: ['d:/a', 'd:/b'], pins: ['d:/b'] } }).seeded, true);
  assert.equal(a.seed({ sessionPins: ['s9'] }).seeded, false, 'Baseline is taken only once');
  const b = createPrefs(pinFile);
  assert.deepEqual(b.get().sessionPins.sort(), ['s1', 's2']);
  assert.deepEqual(b.get().workspaceOrder, { order: ['d:/a', 'd:/b'], pins: ['d:/b'] });
  assert.equal(b.get().initialized, true);
  assert.equal(b.isSessionPinned('s2'), true);
  assert.equal(b.setWorkspaceOrder({ order: ['d:/b', 'd:/a'], pins: [] }), true);
  assert.equal(b.setWorkspaceOrder({ order: ['d:/b', 'd:/a'], pins: [] }), false);
  assert.deepEqual(createPrefs(pinFile).get().workspaceOrder, { order: ['d:/b', 'd:/a'], pins: [] });
  assert.equal(b.removeSessions(['s1', 'nope']), true);
  assert.equal(createPrefs(pinFile).isSessionPinned('s1'), false);
  assert.equal(b.setSessionPin('s2', false), true);
  assert.throws(() => b.setSessionPin('', true), /Invalid/);
  fs.writeFileSync(pinFile, '{bad json');
  assert.deepEqual(createPrefs(pinFile).get().sessionPins, [], 'Damaged file falls back to empty prefs');
} finally { fs.rmSync(pinDir, { recursive: true, force: true }); }
console.log('Workspace retention: counts, oldest-first pruning, active protection, overflow and deletion failures passed');
