const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const read = file => fs.readFileSync(path.join(__dirname, file), 'utf8');
const server = read('server.cjs');
const html = read('public/index.html');
const worker = read('public/sw.js');
new vm.Script(server);
new vm.Script(read('public/mobile.js'));
new vm.Script(worker);
for (const match of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
for (const token of ['dispatchMobileNotification', 'sendNtfyPush', 'sendTelegramPush', 'notificationHistory', 'connectAiHubEventsBridge', 'sseClients', '/api/push/test', '/api/events', 'body.push']) assert.ok(!server.includes(token), token);
for (const token of ['cfg-ntfy', 'cfg-notify', 'showDeviceNotification', 'connectRealtimeEvents', 'Notification.requestPermission']) assert.ok(!html.includes(token), token);
assert.ok(!worker.includes('notificationclick'));
if (fs.existsSync(path.join(__dirname, 'remote-config.json'))) assert.ok(!JSON.parse(read('remote-config.json')).push);
for (const route of ['/api/schedule/countdown', '/api/schedule/snooze', '/api/system/shutdown', '/api/status', '/api/prompt/run']) assert.ok(server.includes(route), route);
const functionsStart = html.indexOf('    function formatShortUptime');
const functionsEnd = html.indexOf('    function highlightThresholdChips', functionsStart);
const context = {};
vm.createContext(context);
vm.runInContext(html.slice(functionsStart, functionsEnd), context);
assert.equal(context.formatShortUptime(7260), '2h 1p');
assert.equal(context.formatCountdownClock(3661), '01:01:01');
console.log('PASS: syntax, removed notification code/config, retained power/scheduler routes, uptime/countdown formatting');
