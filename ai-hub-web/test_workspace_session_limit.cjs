const assert = require('node:assert/strict');
const { MAX_WORKSPACE_SESSIONS, countWorkspaceSessions } = require('./workspace-session-limit.cjs');
assert.equal(MAX_WORKSPACE_SESSIONS, 20);
const stored = [{ id: 'one', name: 'Chat', tempName: 'temp', cwd: 'D:/Project' }];
const existing = { sessionId: 'temp', info: { cwd: '\\\\?\\D:\\PROJECT\\' } };
const pending = { sessionId: 'pending', info: { cwd: 'd:/project/' } };
assert.equal(countWorkspaceSessions('D:/project', stored, [existing, existing, pending]), 2);
assert.equal(countWorkspaceSessions('D:/other', stored, [existing, pending]), 0);
assert.equal(countWorkspaceSessions('D:/project', stored, [{ ...pending, isFinished: true }]), 1);
assert.equal(countWorkspaceSessions('D:/project', stored, [{ sessionId: 'other', resolvedDbId: 'one', info: { cwd: 'D:/project' } }]), 1);
const { makeWorkspaceSessionRoom } = require('./workspace-session-limit.cjs');
const full = Array.from({ length: 20 }, (_, i) => ({ id: String(i), cwd: 'D:/project', created_at: new Date(2026, 0, i + 1).toISOString() }));
const removed = [];
makeWorkspaceSessionRoom('d:/PROJECT', full.slice().reverse(), [], s => s.id === '0', s => removed.push(s.id));
assert.deepEqual(removed, ['1'], 'Oldest by creation date, excluding running sessions');
assert.throws(() => makeWorkspaceSessionRoom('D:/project', full, [], () => true, () => assert.fail('Must not delete running sessions')), /running sessions/);
const over = [...full, { id: 'extra', cwd: 'D:/project', created_at: '2027-01-01' }];
const pruned = [];
makeWorkspaceSessionRoom('D:/project', over, [], () => false, s => pruned.push(s.id));
assert.deepEqual(pruned, ['0', '1']);
assert.throws(() => makeWorkspaceSessionRoom('D:/project', full, [], () => false, () => { throw new Error('Deletion failed'); }), /Deletion failed/);
console.log('Workspace retention: counts, oldest-first pruning, active protection, overflow and deletion failures passed');
